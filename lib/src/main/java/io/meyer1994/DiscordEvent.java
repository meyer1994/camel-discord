    public static DiscordEvent fromEvent(GenericEvent event) {
        return event == null ? null : fromEventType(event.getClass());
    }

    public static DiscordEvent fromEventType(Class<?> eventType) {
        if (eventType == null) {
            return null;
        }

        String simpleName = eventType.getSimpleName();
        if (!simpleName.endsWith("Event")) {
            return null;
        }

        try {
            return valueOf("on" + simpleName.substring(0, simpleName.length() - "Event".length()));
        } catch (IllegalArgumentException e) {
            return null;
        }
    }
